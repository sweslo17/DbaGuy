class Engine:
    """One dev database: its catalogue, the statements that make it, and how to run SQL on it."""

    def __init__(self, name: str, objects: list[tuple[str, str]], create: list[str]) -> None:
        self.name, self.objects, self.create_statements = name, objects, create

    def tables(self) -> set[str]:
        """The catalogue's names in the form a statement may use them: qualified as listed, or bare; lower case."""
        names = {name.lower() for _, name in self.objects}
        return names | {name.rsplit(".", 1)[-1] for name in names}

    def connect(self):
        raise NotImplementedError

    def run(self, conn, sql: str) -> int | None:
        raise NotImplementedError

    def leftovers(self, conn) -> list[str]:
        raise NotImplementedError

    def begin(self, conn) -> None:
        raise NotImplementedError

    def rollback(self, conn) -> None:
        raise NotImplementedError

    def drop(self, conn) -> None:
        for kind, name in self.objects:  # views first: they depend on the tables
            assert name.rsplit(".", 1)[-1].startswith(PREFIX), name  # never anything but a catalogue object
            self.run(conn, f"DROP {kind} IF EXISTS {name}")

    def create(self, conn) -> None:
        self.drop(conn)
        for statement in self.create_statements:
            self.run(conn, statement)


class Postgres(Engine):
    def connect(self):
        return psycopg.connect(host=PG_HOST, port=PG_PORT, user=PG_USER, password=PG_PASSWORD, dbname="dbaguy",
                               autocommit=True, connect_timeout=5)

    def run(self, conn, sql):
        return conn.execute(sql).rowcount

    def leftovers(self, conn):
        rows = conn.execute("SELECT table_schema || '.' || table_name FROM information_schema.tables "
                            "WHERE table_name LIKE %s ORDER BY 1", (PREFIX.replace("_", r"\_") + "%",)).fetchall()
        return [row[0] for row in rows]

    def begin(self, conn):
        conn.autocommit = False

    def rollback(self, conn):
        conn.rollback()
        conn.autocommit = True


class Mysql(Engine):
    def connect(self):
        conn = mysql.connector.connect(**mysql_driver_kwargs())
        conn.autocommit = True
        return conn

    def run(self, conn, sql):
        cursor = conn.cursor()
        try:
            cursor.execute(sql)
            if cursor.with_rows:
                cursor.fetchall()
            return cursor.rowcount
        finally:
            cursor.close()

    def leftovers(self, conn):
        cursor = conn.cursor()
        cursor.execute("SELECT CONCAT(TABLE_SCHEMA, '.', TABLE_NAME) FROM information_schema.TABLES "
                       "WHERE TABLE_NAME LIKE %s ORDER BY 1", (PREFIX.replace("_", r"\_") + "%",))
        names = [row[0] for row in cursor.fetchall()]
        cursor.close()
        return names

    def begin(self, conn):
        conn.start_transaction()

    def rollback(self, conn):
        conn.rollback()


class Mssql(Engine):
    def connect(self):
        return mssql_connect(database="dbaguy")

    def run(self, conn, sql):
        conn.execute_non_query(sql)
        return conn.rows_affected

    def leftovers(self, conn):
        pattern = PREFIX.replace("_", "[_]") + "%"
        conn.execute_query(f"SELECT SCHEMA_NAME(schema_id) + N'.' + name FROM dbaguy.sys.objects "
                           f"WHERE name LIKE N'{pattern}' AND type IN ('U', 'V') ORDER BY 1")
        return [row[0] for row in conn]

    def begin(self, conn):
        conn.execute_non_query("BEGIN TRANSACTION")

    def rollback(self, conn):
        conn.execute_non_query("IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION")


class Sqlite(Engine):
    def connect(self):
        SQLITE_FILE.parent.mkdir(parents=True, exist_ok=True)
        return sqlite3.connect(SQLITE_FILE, isolation_level=None, timeout=1)

    def run(self, conn, sql):
        cursor = conn.execute(sql)
        cursor.fetchone()  # a SELECT under `hold` keeps its read lock while the transaction is open
        return cursor.rowcount

    def leftovers(self, conn):
        rows = conn.execute("SELECT name FROM sqlite_master WHERE name LIKE ? ESCAPE '\\' AND type IN ('table', 'view') "
                            "ORDER BY 1", (PREFIX.replace("_", "\\_") + "%",)).fetchall()
        return [f"{SQLITE_FILE.name}: {row[0]}" for row in rows]

    def begin(self, conn):
        conn.execute("BEGIN")

    def rollback(self, conn):
        conn.execute("ROLLBACK")


ENGINES: dict[str, Engine] = {
    "pg": Postgres("pg", PG, PG_CREATE),
    "mysql": Mysql("mysql", MYSQL, MYSQL_CREATE),
    "mssql": Mssql("mssql", MSSQL, MSSQL_CREATE),
    "sqlite": Sqlite("sqlite", SQLITE, SQLITE_CREATE),
}


_IDENTIFIER = r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?"
_LITERAL = re.compile(r"'(?:[^']|'')*'")
# Left in a statement once its string literals are taken out: a second statement, a comment, a quoted name, a quote.
_NOT_PLAIN = re.compile(r"""--|/\*|[;\\"`$#\[\]']""")
_HEAD = re.compile(
    rf"\s*(?:UPDATE\s+(?P<update>{_IDENTIFIER})\s+SET\b"
    rf"|DELETE\s+FROM\s+(?P<delete>{_IDENTIFIER})(?:\s+WHERE\b|\s*$)"
    rf"|INSERT\s+INTO\s+(?P<insert>{_IDENTIFIER})(?:\s*\(|\s+VALUES\b|\s+DEFAULT\b|\s+SELECT\b)"
    rf"|SELECT\b)",
    re.I,
)
_TABLE_KEYWORD = re.compile(r"\b(?:FROM|JOIN|UPDATE|INTO)\b\s*", re.I)
_TABLE = re.compile(rf"({_IDENTIFIER})(?![\w.])")
# Words that make a statement more than a plain data statement (T-SQL needs no `;` between two statements).
_NOT_DATA = re.compile(
    r"\b(?:DROP|CREATE|ALTER|TRUNCATE|EXEC|EXECUTE|MERGE|GRANT|REVOKE|COPY|CALL|ATTACH|DETACH|PRAGMA|VACUUM|REINDEX"
    r"|BEGIN|COMMIT|ROLLBACK)\b",
    re.I,
)


def scratch_violation(statement: str, engine: Engine) -> str | None:
    """Why `sql` and `hold` refuse `statement` (None: they run it). A safety net against typos, not a sandbox.

    One plain UPDATE / DELETE FROM / INSERT INTO / SELECT; no comment, quoted name, backslash (its meaning differs per
    engine) or `;` outside a string literal (one trailing `;` is fine); every table after FROM, JOIN, UPDATE or INTO, in
    subqueries and in a second statement without `;` too, is a catalogue object of `engine` by its exact name (a name
    that only starts with zz_05b_ is not one); the statement refers to at least one. A false refusal costs a rewrite.
    """
    if "\\" in statement:
        return "no backslash (its meaning differs per engine)"
    plain = _LITERAL.sub(" ", statement).strip()
    plain = plain.removesuffix(";").rstrip()
    if _NOT_PLAIN.search(plain):
        return "one plain statement only (no `;`, comment, quoted name or unterminated literal)"
    head = _HEAD.match(plain)
    if not head:
        return "only UPDATE t SET, DELETE FROM t [WHERE], INSERT INTO t (…|VALUES|DEFAULT|SELECT), or SELECT"
    if _NOT_DATA.search(plain):
        return "data statements only"
    tables = engine.tables()
    named = [name for name in head.groups() if name]
    for keyword in _TABLE_KEYWORD.finditer(plain):
        table = _TABLE.match(plain, keyword.end())
        if not table:
            return "every table must be named after FROM, JOIN, UPDATE and INTO (no subquery in FROM)"
        named.append(table.group(1))
    if not named:
        return f"names no {PREFIX} object"
    unknown = [name for name in named if name.lower() not in tables]
    return f"not a {PREFIX} catalogue object of {engine.name}: {unknown[0]}" if unknown else None


def _scratch_statement(engine: Engine, statement: str) -> str:
    problem = scratch_violation(statement, engine)
    if problem:
        sys.exit(f"Refused: {problem}")
    return statement


def _engines(names: list[str]) -> list[Engine]:
    unknown = [name for name in names if name not in ENGINES]
    if unknown:
        sys.exit(f"Unknown engine(s): {', '.join(unknown)} (pg, mysql, mssql, sqlite)")
    return [ENGINES[name] for name in names] or list(ENGINES.values())


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    command, rest = argv[0], argv[1:]
    if command in ("create", "drop"):
        for engine in _engines(rest):
            conn = engine.connect()
            try:
                started = time.monotonic()
                getattr(engine, command)(conn)
                print(f"{engine.name}: {command} done in {time.monotonic() - started:.1f} s")
            finally:
                conn.close()
        return 0
    if command == "check":
        left = []
        for engine in ENGINES.values():
            conn = engine.connect()
            try:
                left += [f"{engine.name} {name}" for name in engine.leftovers(conn)]
            finally:
                conn.close()
        print("\n".join(left) if left else f"No {PREFIX} object left")
        return 1 if left else 0
    if command == "sql" and len(rest) == 2:
        engine = _engines([rest[0]])[0]
        statement = _scratch_statement(engine, rest[1])
        conn = engine.connect()
        try:
            print(f"{engine.name}: {engine.run(conn, statement)} row(s)")
        finally:
            conn.close()
        return 0
    if command == "hold" and len(rest) == 3:
        engine, seconds = _engines([rest[0]])[0], float(rest[1])
        statement = _scratch_statement(engine, rest[2])
        conn = engine.connect()
        try:
            engine.begin(conn)
            engine.run(conn, statement)
            print(f"{engine.name}: holding for {seconds:g} s", flush=True)
            time.sleep(seconds)
            engine.rollback(conn)
            print(f"{engine.name}: rolled back")
        finally:
            conn.close()
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
