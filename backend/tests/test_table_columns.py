def test_sqlite_a_view_over_a_dropped_table_is_still_a_read_only_target(tmp_path):
    """Its pragma_table_xinfo fails (no such table), so grid editing never reads a view's columns (⑤ unchanged)."""
    db = scratch_db("sqlite", tmp_path)
    with dropping(db) as made:
        table, view = scratch_name("cols_gone"), scratch_name("cols_view")
        made += [("VIEW", view), ("TABLE", table)]
        db.execute(f"CREATE TABLE {table} (a INT)", f"CREATE VIEW {view} AS SELECT a FROM {table}",
                   f"DROP TABLE {table}")
        conn = db.open()
        try:
            assert conn.edit_target(db.path(view, "view")).reason == VIEWS
            with pytest.raises(StatementError, match="no such table"):
                conn.table_columns(db.path(view, "view"))
        finally:
            conn.close()
