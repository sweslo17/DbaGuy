import psycopg

from ...domain.errors import NotFound, ValidationFailed
from ...domain.metadata import NodeKind, ObjectDetail, PathSegment
from ..sql_text import qualified_pg, quote_ident_pg, quote_literal
from .introspection import PgColumn, relation_oid, table_columns

_CONSTRAINTS_SQL = """
SELECT conname, pg_get_constraintdef(oid, true) FROM pg_constraint
WHERE conrelid = %(oid)s AND contype IN ('p', 'u', 'c', 'f', 'x')
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'f' THEN 3 ELSE 4 END, conname
"""
_EXTRA_INDEXES_SQL = """
SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i
WHERE i.indrelid = %(oid)s
  AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid AND k.conrelid = i.indrelid)
ORDER BY 1
"""


def _one(conn: psycopg.Connection, sql: str, params: dict, what: str):
    row = conn.execute(sql, params).fetchone()
    if row is None or row[0] is None:
        raise NotFound(f"{what} not found")
    return row


def _column_def(col: PgColumn) -> str:
    parts = [quote_ident_pg(col.name), col.type]
    if col.generated in ("s", "v"):
        parts.append(f"GENERATED ALWAYS AS ({col.default}) {'STORED' if col.generated == 's' else 'VIRTUAL'}")
    elif col.identity == "a":
        parts.append("GENERATED ALWAYS AS IDENTITY")
    elif col.identity == "d":
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    elif col.default is not None:
        parts.append(f"DEFAULT {col.default}")
    if col.not_null and not col.identity:
        parts.append("NOT NULL")
    return " ".join(parts)


def table_ddl(conn: psycopg.Connection, schema: str, name: str) -> tuple[str, list[PgColumn], str | None]:
    qname = qualified_pg(schema, name)
    oid = relation_oid(conn, qname)
    relkind, is_partition, partkey, comment, parent, bound, persistence = conn.execute(
        "SELECT c.relkind::text, c.relispartition, pg_get_partkeydef(c.oid), obj_description(c.oid, 'pg_class'), "
        "(SELECT h.inhparent::regclass::text FROM pg_inherits h WHERE h.inhrelid = c.oid LIMIT 1), "
        "pg_get_expr(c.relpartbound, c.oid), c.relpersistence::text FROM pg_class c WHERE c.oid = %(oid)s",
        {"oid": oid},
    ).fetchone()
    columns = table_columns(conn, oid)
    blocks: list[str] = []
    if is_partition:
        sub_partitioning = f" PARTITION BY {partkey}" if relkind == "p" else ""  # a partition can itself be partitioned
        blocks.append(f"CREATE TABLE {qname} PARTITION OF {parent}\n    {bound}{sub_partitioning};")
    else:
        body = [_column_def(c) for c in columns]
        body += [f"CONSTRAINT {quote_ident_pg(n)} {d}" for n, d in conn.execute(_CONSTRAINTS_SQL, {"oid": oid})]
        unlogged = "UNLOGGED " if persistence == "u" else ""
        statement = f"CREATE {unlogged}TABLE {qname} (\n    " + ",\n    ".join(body) + "\n)"
        if relkind == "p":
            statement += f" PARTITION BY {partkey}"
        blocks.append(statement + ";")
    indexes = [f"{d};" for (d,) in conn.execute(_EXTRA_INDEXES_SQL, {"oid": oid})]
    if indexes:
        blocks.append("\n".join(indexes))
    comments = []
    if comment:
        comments.append(f"COMMENT ON TABLE {qname} IS {quote_literal(comment)};")
    comments += [
        f"COMMENT ON COLUMN {qname}.{quote_ident_pg(c.name)} IS {quote_literal(c.comment)};" for c in columns if c.comment
    ]
    if comments:
        blocks.append("\n".join(comments))
    return "\n\n".join(blocks), columns, comment


def _view_ddl(conn: psycopg.Connection, qname: str, materialized: bool) -> str:
    (definition,) = _one(conn, "SELECT pg_get_viewdef(to_regclass(%(q)s), true)", {"q": qname}, qname)
    keyword = "CREATE MATERIALIZED VIEW" if materialized else "CREATE OR REPLACE VIEW"
    return f"{keyword} {qname} AS\n{definition.rstrip().rstrip(';')};"


def _function_ddl(conn: psycopg.Connection, schema: str, signature: str) -> str:
    name, _, args = signature.partition("(")
    regproc = f"{qualified_pg(schema, name)}({args}"
    (definition,) = _one(
        conn, "SELECT pg_get_functiondef(p) FROM to_regprocedure(%(sig)s) p", {"sig": regproc}, signature
    )
    return definition.rstrip() + ";"


def _sequence_ddl(conn: psycopg.Connection, qname: str) -> str:
    type_, start, inc, minv, maxv, cache, cycle = _one(
        conn,
        "SELECT format_type(s.seqtypid, NULL), s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, s.seqcycle "
        "FROM pg_sequence s WHERE s.seqrelid = to_regclass(%(q)s)",
        {"q": qname},
        qname,
    )
    return (
        f"CREATE SEQUENCE {qname}\n    AS {type_}\n    INCREMENT BY {inc}\n    MINVALUE {minv}\n"
        f"    MAXVALUE {maxv}\n    START WITH {start}\n    CACHE {cache}\n    {'CYCLE' if cycle else 'NO CYCLE'};"
    )


def _type_ddl(conn: psycopg.Connection, qname: str) -> str:
    oid, typtype, base, not_null, default, typrelid = _one(
        conn,
        "SELECT t.oid, t.typtype::text, format_type(t.typbasetype, t.typtypmod), t.typnotnull, t.typdefault, t.typrelid "
        "FROM pg_type t WHERE t.oid = to_regtype(%(q)s)",
        {"q": qname},
        qname,
    )
    if typtype == "e":
        labels = [quote_literal(label) for (label,) in conn.execute(
            "SELECT enumlabel FROM pg_enum WHERE enumtypid = %(oid)s ORDER BY enumsortorder", {"oid": oid})]
        return f"CREATE TYPE {qname} AS ENUM ({', '.join(labels)});"
    if typtype == "d":
        statement = f"CREATE DOMAIN {qname} AS {base}"
        if default is not None:
            statement += f" DEFAULT {default}"
        if not_null:
            statement += " NOT NULL"
        for name, definition in conn.execute(
            "SELECT conname, pg_get_constraintdef(oid, true) FROM pg_constraint WHERE contypid = %(oid)s ORDER BY conname",
            {"oid": oid},
        ):
            statement += f"\n    CONSTRAINT {quote_ident_pg(name)} {definition}"
        return statement + ";"
    if typtype == "c":
        attributes = [f"{quote_ident_pg(n)} {t}" for n, t in conn.execute(
            "SELECT attname, format_type(atttypid, atttypmod) FROM pg_attribute "
            "WHERE attrelid = %(rel)s AND attnum > 0 AND NOT attisdropped ORDER BY attnum",
            {"rel": typrelid},
        )]
        return f"CREATE TYPE {qname} AS (\n    " + ",\n    ".join(attributes) + "\n);"
    raise ValidationFailed(f"No DDL available for type kind '{typtype}'")


def object_detail(conn: psycopg.Connection, path: list[PathSegment]) -> ObjectDetail:
    rel = path[1:]
    if not rel:
        raise ValidationFailed("No details available for a database")
    last = path[-1]
    schema = rel[0].name
    base = {"path": path, "kind": last.kind, "name": last.name}
    if last.kind == NodeKind.SCHEMA:
        return ObjectDetail(**base, ddl=f"CREATE SCHEMA {quote_ident_pg(schema)};")
    qname = qualified_pg(schema, last.name)
    match last.kind:
        case NodeKind.TABLE | NodeKind.PARTITION:
            ddl, columns, comment = table_ddl(conn, schema, last.name)
            return ObjectDetail(**base, ddl=ddl, ddl_is_generated=True, columns=[c.info() for c in columns], comment=comment)
        case NodeKind.VIEW | NodeKind.MATERIALIZED_VIEW:
            columns = [c.info() for c in table_columns(conn, relation_oid(conn, qname))]
            return ObjectDetail(**base, ddl=_view_ddl(conn, qname, last.kind == NodeKind.MATERIALIZED_VIEW), columns=columns)
        case NodeKind.FUNCTION | NodeKind.PROCEDURE:
            return ObjectDetail(**base, ddl=_function_ddl(conn, schema, last.name))
        case NodeKind.SEQUENCE:
            return ObjectDetail(**base, ddl=_sequence_ddl(conn, qname))
        case NodeKind.TYPE:
            return ObjectDetail(**base, ddl=_type_ddl(conn, qname))
        case NodeKind.INDEX:
            (definition,) = _one(conn, "SELECT pg_get_indexdef(to_regclass(%(q)s))", {"q": qname}, qname)
            return ObjectDetail(**base, ddl=f"{definition};")
        case NodeKind.TRIGGER:
            table = qualified_pg(schema, rel[-3].name)  # rel[-2] is the folder, rel[-3] the owning object
            (definition,) = _one(
                conn,
                "SELECT pg_get_triggerdef(t.oid, true) FROM pg_trigger t WHERE t.tgrelid = to_regclass(%(t)s) AND t.tgname = %(n)s",
                {"t": table, "n": last.name},
                last.name,
            )
            return ObjectDetail(**base, ddl=f"{definition};")
        case NodeKind.COLUMN:
            table_oid = relation_oid(conn, qualified_pg(schema, rel[-3].name))
            columns = [c.info() for c in table_columns(conn, table_oid) if c.name == last.name]
            if not columns:
                raise NotFound(f"Column {last.name} not found")
            return ObjectDetail(**base, columns=columns)
    raise ValidationFailed(f"No details available for {last.kind}")
